/** WebUI 的配置组；路径必须落在 `worlds.listen.` 段内，且每个键都在 DEFAULTS 里有对应项。 */
export function configGroup(language = 'zh') {
  const t = text(language).config;
  const K = `worlds.${ID}`;
  return {
    id: `world:${ID}`,
    owner: `world:${ID}`,
    schema: {
      type: 'object',
      title: t.title,
      properties: {
        [`${K}.enabled`]: { type: 'boolean', title: t.enabled, description: t.enabledDesc, 'x-hot': true },
        [`${K}.source`]: {
          type: 'string',
          title: t.source,
          description: t.sourceDesc,
          enum: [...SOURCES],
          'x-hot': true,
        },
        [`${K}.app`]: { type: 'string', title: t.app, description: t.appDesc, 'x-hot': true },
        [`${K}.autoListen`]: { type: 'boolean', title: t.autoListen, description: t.autoListenDesc, 'x-hot': true },
        [`${K}.control`]: {
          type: 'string',
          title: t.control,
          description: t.controlDesc,
          enum: [...CONTROLS],
          'x-hot': true,
        },
        [`${K}.wake`]: {
          type: 'string',
          title: t.wake,
          description: t.wakeDesc,
          enum: [...WAKES],
          'x-hot': true,
        },
        [`${K}.autoStopMinutes`]: {
          type: 'integer',
          title: t.autoStop,
          description: t.autoStopDesc,
          minimum: 0,
          maximum: 600,
          'x-suffix': '分钟',
          'x-hot': true,
        },
        [`${K}.thresholdDb`]: {
          type: 'integer',
          title: t.threshold,
          description: t.thresholdDesc,
          minimum: -80,
          maximum: -10,
          'x-suffix': 'dB',
          'x-hot': true,
        },
        [`${K}.minSpeechMs`]: {
          type: 'integer',
          title: t.minSpeech,
          description: t.minSpeechDesc,
          minimum: 50,
          maximum: 2000,
          multipleOf: 10,
          'x-suffix': 'ms',
          'x-hot': true,
        },
        [`${K}.silenceMs`]: {
          type: 'integer',
          title: t.silence,
          description: t.silenceDesc,
          minimum: 150,
          maximum: 5000,
          multipleOf: 50,
          'x-suffix': 'ms',
          'x-hot': true,
        },
        [`${K}.maxUtteranceMs`]: {
          type: 'integer',
          title: t.maxUtterance,
          description: t.maxUtteranceDesc,
          minimum: 2000,
          maximum: 120000,
          multipleOf: 1000,
          'x-suffix': 'ms',
          'x-hot': true,
        },
        [`${K}.preRollMs`]: {
          type: 'integer',
          title: t.preRoll,
          description: t.preRollDesc,
          minimum: 0,
          maximum: 1000,
          multipleOf: 20,
          'x-suffix': 'ms',
          'x-hot': true,
        },
        [`${K}.minUtteranceMs`]: {
          type: 'integer',
          title: t.minUtterance,
          description: t.minUtteranceDesc,
          minimum: 100,
          maximum: 5000,
          multipleOf: 20,
          'x-suffix': 'ms',
          'x-hot': true,
        },
        [`${K}.vad`]: {
          type: 'string',
          title: t.vad,
          description: t.vadDesc,
          enum: [...VADS],
          'x-hot': true,
        },
        [`${K}.sileroThreshold`]: {
          type: 'number',
          title: t.sileroThreshold,
          description: t.sileroThresholdDesc,
          minimum: 0.1,
          maximum: 0.9,
          multipleOf: 0.05,
          'x-hot': true,
        },
        [`${K}.sileroModel`]: {
          type: 'string',
          title: t.sileroModel,
          description: t.sileroModelDesc,
          'x-path': { kind: 'file' },
          'x-hot': true,
        },
        [`${K}.maxEventsPerMinute`]: {
          type: 'integer',
          title: t.rate,
          description: t.rateDesc,
          minimum: 0,
          maximum: 600,
          multipleOf: 5,
          'x-suffix': ' 块/分',
          'x-hot': true,
        },
        [`${K}.saveDir`]: {
          type: 'string',
          title: t.saveDir,
          description: t.saveDirDesc,
          'x-path': { kind: 'directory' },
          'x-hot': true,
        },
        [`${K}.keep`]: {
          type: 'integer',
          title: t.keep,
          description: t.keepDesc,
          minimum: 0,
          maximum: 5000,
          multipleOf: 10,
          'x-suffix': ' 条',
        },
        [`${K}.pushToConsole`]: { type: 'boolean', title: t.push, description: t.pushDesc, 'x-hot': true },
      },
    },
  };
}
